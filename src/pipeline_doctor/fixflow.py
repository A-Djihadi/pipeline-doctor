"""Orchestration d'une tentative de correctif (propose ou PR draft).

Mappe chaque issue vers une ligne de `fix_proposals` et, pour `proposed`/`pr_opened`,
vers un message Slack. Ne leve jamais : toute exception inattendue devient une ligne
`error` avec `reason = "exception:<ClassName>"`.
"""
import json
import time
from dataclasses import dataclass

from . import fixer, github, github_write, journal, llm
from .fixer import BRANCH_PREFIX, FIX_PROMPT_VERSION, FixRejected
from .github_write import GitHubWriteError
from .slack import build_fix_payload, send


@dataclass(frozen=True)
class FixSettings:
    mode: str                 # "propose" | "pr"
    read_token: str           # GITHUB_TOKEN
    fork: str | None          # PD_FIX_FORK (pr)
    write_token: str | None   # PD_FIX_TOKEN (pr)
    max_per_day: int = 3


def _default_ask(system: str, user: str) -> dict:
    return llm.chat(system, user, user_template="{log}", timeout=300)[0]


def _row(repo, run, status, reason=None, files=None, diff=None, pr_number=None,
         pr_url=None, head_branch=None, model=None) -> dict:
    return {
        "source": "github",
        "source_ref": str(run.get("id")),
        "repo": repo,
        "base_branch": run.get("head_branch"),
        "base_sha": run.get("head_sha"),
        "head_branch": head_branch,
        "status": status,
        "reason": reason,
        "files": files,
        "diff": diff,
        "pr_number": pr_number,
        "pr_url": pr_url,
        "model": model,
        "prompt_version": FIX_PROMPT_VERSION,
    }


def _finish(conn, row: dict, dry_run: bool) -> dict:
    if not dry_run:
        journal.record_fix(conn, row)
    return row


def _fence(text: str) -> str:
    """Enveloppe dans un bloc code dont la cloture a un backtick de plus que la
    plus longue suite de backticks du contenu (min 3). Texte coupe a 1000 chars."""
    text = text[:1000]
    longest = run = 0
    for ch in text:
        if ch == "`":
            run += 1
            longest = max(longest, run)
        else:
            run = 0
    fence = "`" * max(3, longest + 1)
    return f"{fence}\n{text}\n{fence}"


def _commit_message(diagnosis: dict, run: dict, model: str) -> str:
    category = diagnosis.get("category", "unknown")
    run_id = run.get("id")
    return (f"fix: {category} failure in run {run_id} (pipeline-doctor)\n\n"
            f"Proposed by pipeline-doctor with local model {model}. "
            f"Human review required before merge.")


def _pr_title(diagnosis: dict, run: dict) -> str:
    category = diagnosis.get("category", "unknown")
    base = run.get("head_branch", "-")
    run_id = run.get("id")
    return f"fix(pipeline-doctor): {category} failure on {base} (run {run_id})"


def _pr_body(diagnosis: dict, proposal, run: dict, repo: str, model: str) -> str:
    category = diagnosis.get("category", "unknown")
    run_id = run.get("id")
    run_link = github.run_url(repo, str(run_id))
    sha = str(run.get("head_sha", ""))[:12]
    cause = str(diagnosis.get("cause", ""))
    evidence = "\n".join(str(e) for e in diagnosis.get("evidence", []))
    return "\n".join([
        "> [!WARNING]",
        f"> Generated by a **local LLM** ({model}, prompt {FIX_PROMPT_VERSION}) from a CI log.",
        "> Review every line. pipeline-doctor never merges, approves or runs CI on this PR.",
        "",
        f"**Failed run:** {run_link} · **Commit:** {sha} · **Category:** {category}",
        "",
        "### Diagnosis",
        _fence(cause),
        "",
        "### Evidence (verbatim from the sanitized log)",
        _fence(evidence),
        "",
        "### Model summary",
        _fence(proposal.summary),
        "",
        "### Guards passed",
        "eligibility · path denylist · secret scan (0 matches) · bypass patterns · ≤3 files / ≤40 lines",
        "",
        "### How to validate",
        "1. Read the diff. 2. Approve the fork workflow run (Actions). 3. If CI is green and the change",
        "is right: mark ready, approve, merge. Otherwise close the PR.",
    ])


def _payload(repo, run, status, reason, summary, diff, pr_url) -> dict:
    return build_fix_payload(repo, run.get("id"), github.run_url(repo, str(run.get("id"))),
                             status, reason, summary, diff, pr_url)


def _send_fix(webhook, repo, run, status, reason, summary, diff, pr_url) -> None:
    send(webhook, _payload(repo, run, status, reason, summary, diff, pr_url))


def run_fix(conn, repo: str, run: dict, diagnosis: dict | None, source: str,
            cleaned_log: str, settings: FixSettings, webhook: str, dry_run: bool,
            *, ask=None) -> dict:
    """Une tentative de correctif. Retourne la ligne journalisee (ou qui le serait)."""
    run_id = run.get("id")
    model = llm.OLLAMA_MODEL
    candidates = None
    try:
        reason = fixer.eligibility(diagnosis, cleaned_log, source=source)
        if reason:
            return _finish(conn, _row(repo, run, "skipped", reason, model=model), dry_run)

        head_repo = (run.get("head_repository") or {}).get("full_name")
        if head_repo != repo:
            return _finish(conn, _row(repo, run, "skipped", "fork_run", model=model), dry_run)
        head_branch = run.get("head_branch") or ""
        if head_branch.startswith(BRANCH_PREFIX):
            return _finish(conn, _row(repo, run, "skipped", "own_branch", model=model), dry_run)
        head_sha = run.get("head_sha")
        if github.branch_sha(repo, head_branch, settings.read_token) != head_sha:
            return _finish(conn, _row(repo, run, "skipped", "stale", model=model), dry_run)
        if settings.mode == "pr":
            fork_owner = (settings.fork or "").split("/")[0]
            if github.open_fix_prs(repo, head_branch, fork_owner, settings.read_token):
                return _finish(conn, _row(repo, run, "skipped", "open_pr_exists", model=model), dry_run)
        since_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(time.time() - 86400))
        if journal.fixes_since(conn, repo, since_iso) >= settings.max_per_day:
            return _finish(conn, _row(repo, run, "skipped", "daily_limit", model=model), dry_run)

        tree, truncated = github.get_tree(repo, head_sha, settings.read_token)
        if truncated:
            return _finish(conn, _row(repo, run, "skipped", "tree_truncated", model=model), dry_run)

        candidates = fixer.candidate_paths(cleaned_log, tree, diagnosis.get("category"))
        if not candidates:
            return _finish(conn, _row(repo, run, "skipped", "no_candidate_files", model=model), dry_run)

        fetched = {p: github.get_file(repo, p, head_sha, settings.read_token) for p in candidates}
        files = fixer.select_files(fetched)

        proposal = fixer.propose(diagnosis, cleaned_log, files, ask or _default_ask)

        if dry_run:
            print(json.dumps(_payload(repo, run, "proposed", None, proposal.summary,
                                      proposal.diff, None), ensure_ascii=False, indent=2))
            return _row(repo, run, "proposed", files=list(proposal.files),
                        diff=proposal.diff, model=model)

        if settings.mode == "pr":
            fork = settings.fork
            fork_owner = fork.split("/")[0]
            github_write.sync_fork(fork, head_branch, settings.write_token)
            if github.branch_sha(fork, head_branch, settings.write_token) != head_sha:
                return _finish(conn, _row(repo, run, "error", "fork_out_of_sync", model=model), dry_run)
            message = _commit_message(diagnosis, run, model)
            new_sha = github_write.commit_files(fork, head_sha, proposal.patched,
                                                message, settings.write_token)
            branch = BRANCH_PREFIX + str(run_id)
            github_write.create_branch(fork, branch, new_sha, settings.write_token)
            title = _pr_title(diagnosis, run)
            body = _pr_body(diagnosis, proposal, run, repo, model)
            pr_number, pr_url = github_write.open_draft_pr(
                repo, f"{fork_owner}:{branch}", head_branch, title, body, settings.write_token)
            row = _row(repo, run, "pr_opened", files=list(proposal.files), diff=proposal.diff,
                       pr_number=pr_number, pr_url=pr_url, head_branch=branch, model=model)
        else:
            row = _row(repo, run, "proposed", files=list(proposal.files),
                       diff=proposal.diff, model=model)

        _finish(conn, row, dry_run=False)
        if webhook:
            _send_fix(webhook, repo, run, row["status"], row.get("reason"),
                      proposal.summary, proposal.diff, row.get("pr_url"))
        return row

    except FixRejected as exc:
        return _finish(conn, _row(repo, run, exc.status, exc.reason, files=candidates, model=model),
                       dry_run)
    except GitHubWriteError as exc:
        return _finish(conn, _row(repo, run, "error", exc.reason, files=candidates, model=model),
                       dry_run)
    except Exception as exc:  # defence en profondeur : jamais de remontee
        return _finish(conn, _row(repo, run, "error", f"exception:{type(exc).__name__}",
                                  files=candidates, model=model), dry_run)
